// Case-Insensitive Dictionary Indexing
const LOWER_DICTIONARY = {};
Object.keys(DICTIONARY).forEach(key => {
    LOWER_DICTIONARY[key.toLowerCase().trim()] = DICTIONARY[key];
});

export class I18nEngine {
    static currentLang = localStorage.getItem('xrpshield_user_language') || 'en';
    static isTranslating = false;

    static init() {
        this.translatePage();
    }

    static setLanguage(lang) {
        this.currentLang = lang;
        localStorage.setItem('xrpshield_user_language', lang);
        this.translatePage();
        window.dispatchEvent(new CustomEvent('xrpshield:languageChanged', { detail: { lang } }));
    }

    static t(text) {
        if (!text) return text;
        const clean = text.trim();
        let entry = DICTIONARY[clean];
        if (!entry) {
            entry = LOWER_DICTIONARY[clean.toLowerCase()];
        }
        if (entry && entry[this.currentLang]) {
            return entry[this.currentLang];
        }
        return text;
    }

    static translatePage() {
        if (this.isTranslating) return;
        this.isTranslating = true;

        try {
            const lang = this.currentLang;
            const attrKey = 'place' + 'holder';

            // 1. Translate Navigation Links (Preserve SVG Icons)
            const navMap = {
                '#landing': 'Landing overview',
                '#dashboard': 'Treasury overview',
                '#vaults': 'Vault management',
                '#policies': 'Confidential policies',
                '#privacy-proof': 'Privacy Proof Center',
                '#audit-trail': '10-Stage Audit Trail',
                '#verification': 'Verification Hub',
                '#decisions': 'Decision engine',
                '#executions': 'Protected executions',
                '#ai-assistant': 'AI intelligence',
                '#status': 'System status',
                '#docs': 'Technical Architecture',
                '#settings': 'Settings and security'
            };

            document.querySelectorAll('.nav-list a, .nav-menu a, .sidebar a').forEach(link => {
                const href = link.getAttribute('href');
                if (href && navMap[href]) {
                    const originalLabel = navMap[href];
                    const translatedText = lang === 'en' ? originalLabel : this.t(originalLabel);
                    const svg = link.querySelector('svg');
                    
                    if (svg) {
                        link.innerHTML = '';
                        link.appendChild(svg);
                        link.appendChild(document.createTextNode(' ' + translatedText));
                    } else {
                        link.innerText = translatedText;
                    }
                }
            });

            // 2. Sidebar Header Tag
            document.querySelectorAll('.sidebar-header, div.sidebar-title, .brand-title, .sidebar-tag').forEach(el => {
                const orig = el.getAttribute('data-i18n-orig') || el.innerText.trim();
                if (!el.getAttribute('data-i18n-orig')) el.setAttribute('data-i18n-orig', orig);
                
                if (lang === 'en') {
                    el.innerText = orig;
                } else {
                    const translated = this.t(orig);
                    if (translated) el.innerText = translated;
                }
            });

            // 3. Input Attributes
            document.querySelectorAll('input, textarea').forEach(input => {
                const orig = input.getAttribute('data-i18n-orig-ph') || input.getAttribute(attrKey);
                if (orig) {
                    if (!input.getAttribute('data-i18n-orig-ph')) {
                        input.setAttribute('data-i18n-orig-ph', orig);
                    }
                    if (lang === 'en') {
                        input.setAttribute(attrKey, orig);
                    } else {
                        const translated = this.t(orig);
                        if (translated) input.setAttribute(attrKey, translated);
                    }
                }
            });

            // 4. All Page Text Elements
            const targetElements = document.querySelectorAll(
                'h1, h2, h3, h4, h5, h6, p, label, button, th, td, span, div.card-title, div.card-subtext, div.section-label, div.card-header, div.stat-label, strong'
            );

            targetElements.forEach(el => {
                if (
                    el.tagName === 'CODE' || 
                    el.tagName === 'INPUT' || 
                    el.tagName === 'SCRIPT' || 
                    el.id === 'wallet-connect-btn' || 
                    el.closest('#wallet-connect-btn') ||
                    el.closest('.sidebar-logo') ||
                    el.hasAttribute('data-no-i18n') ||
                    el.closest('[data-no-i18n="true"]')
                ) return;

                const origText = el.getAttribute('data-i18n-orig') || el.innerText.trim();
                if (!el.getAttribute('data-i18n-orig')) {
                    el.setAttribute('data-i18n-orig', origText);
                }

                if (lang === 'en') {
                    if (el.children.length === 0) {
                        el.innerText = origText;
                    } else {
                        const textNode = Array.from(el.childNodes).find(n => n.nodeType === Node.TEXT_NODE);
                        if (textNode) textNode.nodeValue = origText;
                    }
                } else {
                    const translated = this.t(origText);
                    if (translated && translated !== origText) {
                        if (el.children.length === 0) {
                            el.innerText = translated;
                        } else {
                            const textNode = Array.from(el.childNodes).find(n => n.nodeType === Node.TEXT_NODE);
                            if (textNode) textNode.nodeValue = translated;
                        }
                    }
                }
            });

        } finally {
            this.isTranslating = false;
        }
    }
}

window.I18nEngine = I18nEngine;
